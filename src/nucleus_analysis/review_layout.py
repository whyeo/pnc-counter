"""Native, fixed-panel review layout. Analysis and edits live in the editor."""

import tkinter as tk
from tkinter import ttk


def build_review_layout(editor, methods):
    e = editor
    e.window = tk.Toplevel(e.parent)
    from . import __version__

    e.window.title(f"PNC Counter {__version__} - Review nuclei")
    e.window.geometry("1180x800")
    e.window.minsize(950, 650)
    e.window.protocol("WM_DELETE_WINDOW", e.close)
    e.window.columnconfigure(0, weight=1)
    e.window.rowconfigure(2, weight=1)
    e.buttons = []
    style = ttk.Style(e.window)
    font = ("Segoe UI", 10)
    style.configure("Review.TButton", padding=(9, 5), font=font)
    style.configure("Review.TRadiobutton", padding=(7, 4), font=font)
    style.configure("Review.TLabel", font=font)
    style.configure("ReviewTitle.TLabel", font=("Segoe UI", 12, "bold"))
    style.configure("ReviewMuted.TLabel", foreground="#596574", font=("Segoe UI", 9))
    style.configure("ReviewPane.TFrame", background="#ffffff")
    style.configure("ReviewPane.TLabel", background="#ffffff", font=font)
    style.configure("ReviewHeading.TLabel", background="#ffffff", font=("Segoe UI", 10, "bold"))

    header = ttk.Frame(e.window, padding=(14, 10))
    header.grid(row=0, column=0, sticky="ew")
    header.columnconfigure(0, weight=1)
    source = e.session.projections.metadata.get("source")
    from pathlib import Path

    filename = Path(source).name if source else e.directory.name
    ttk.Label(header, text=filename, style="ReviewTitle.TLabel").grid(row=0, column=0, sticky="w")
    e.save_state = tk.StringVar()
    ttk.Label(header, textvariable=e.save_state, style="ReviewMuted.TLabel").grid(row=1, column=0, sticky="w")
    e.stats = tk.StringVar()
    ttk.Label(header, textvariable=e.stats, style="ReviewTitle.TLabel").grid(row=0, column=1, rowspan=2, padx=18)
    e.save_button = e.button(header, "Save review", e.save)
    e.save_button.grid(row=0, column=2, rowspan=2)

    threshold = ttk.Frame(e.window, padding=(14, 7))
    threshold.grid(row=1, column=0, sticky="ew")
    threshold.columnconfigure(1, weight=1)
    e.threshold_title = tk.StringVar(value="PNC threshold")
    ttk.Label(threshold, textvariable=e.threshold_title, style="Review.TLabel").grid(row=0, column=0, padx=(0, 16))
    e.pnc_method = tk.StringVar(value=next(k for k, v in methods.items() if v == e.session.config.pnc_mode))
    e.pnc_sensitivity = tk.DoubleVar(value=e.session.config.pnc_sensitivity)
    e.pnc_enrichment = tk.DoubleVar(value=e.session.config.pnc_enrichment_threshold)
    e.pnc_enrichment_text = tk.StringVar(value=f"{e.pnc_enrichment.get():.2f}")
    e.pnc_slider = ttk.Scale(threshold, from_=0, to=100, variable=e.pnc_sensitivity, command=e.schedule_pnc_preview)
    e.pnc_slider.grid(row=0, column=1, sticky="ew", padx=(0, 14))
    e.pnc_direction = tk.StringVar()
    ttk.Label(threshold, textvariable=e.pnc_direction, style="ReviewMuted.TLabel").grid(row=1, column=1, sticky="ew")
    e.enrichment_controls = ttk.Frame(threshold)
    e.enrichment_controls.grid(row=0, column=2, rowspan=2)
    e.enrichment_entry = ttk.Spinbox(e.enrichment_controls, from_=0.1, to=20, increment=.05,
        textvariable=e.pnc_enrichment_text, format="%.2f", width=6, command=e.apply_enrichment_entry, font=font)
    e.enrichment_entry.pack(side="left")
    e.enrichment_entry.bind("<Return>", e.apply_enrichment_entry)
    e.enrichment_entry.bind("<FocusOut>", e.apply_enrichment_entry)
    ttk.Label(e.enrichment_controls, text=" × background", style="Review.TLabel").pack(side="left", padx=(0, 12))
    e.button(e.enrichment_controls, "Reset", e.reset_enrichment).pack(side="left")
    e.pnc_readout = tk.StringVar()
    e.pnc_readout_label = ttk.Label(threshold, textvariable=e.pnc_readout, style="Review.TLabel")

    body = ttk.Frame(e.window)
    body.grid(row=2, column=0, sticky="nsew")
    body.columnconfigure(0, weight=1)
    body.rowconfigure(0, weight=1)
    image_frame = ttk.Frame(body)
    image_frame.grid(row=0, column=0, sticky="nsew")
    image_frame.columnconfigure(0, weight=1)
    image_frame.rowconfigure(2, weight=1)
    toolbar = ttk.Frame(image_frame, padding=(10, 6))
    toolbar.grid(row=0, column=0, columnspan=2, sticky="ew")
    e.tool = tk.StringVar(value="Select")
    for label, mode in (("Select", "Select"), ("Add nucleus", "Add"), ("Edit outline", "Redraw")):
        widget = ttk.Radiobutton(toolbar, text=label, variable=e.tool, value=mode,
                                 command=e.change_tool, style="Review.TRadiobutton")
        widget.pack(side="left", padx=(0, 5))
        e.buttons.append(widget)
    e.button(toolbar, "Undo", e.undo).pack(side="left", padx=5)
    e.channel = tk.StringVar(value="PNC")
    channels = ttk.Combobox(toolbar, values=("PNC", "DAPI + PNC", "DAPI", "PNC threshold"),
                            textvariable=e.channel, state="readonly", width=13)
    channels.pack(side="right", padx=4)
    channels.bind("<<ComboboxSelected>>", lambda _event: e.render())
    e.outline_controls = ttk.Frame(image_frame, padding=(12, 4))
    e.button(e.outline_controls, "Finish (Enter)", e.finish_outline).pack(side="left")
    e.button(e.outline_controls, "Cancel (Esc)", e.cancel_outline).pack(side="left", padx=6)
    e.canvas = tk.Canvas(image_frame, background="#171b24", highlightthickness=0)
    e.canvas.grid(row=2, column=0, sticky="nsew")
    horizontal = ttk.Scrollbar(image_frame, orient="horizontal", command=e.canvas.xview)
    vertical = ttk.Scrollbar(image_frame, orient="vertical", command=e.canvas.yview)
    horizontal.grid(row=3, column=0, sticky="ew")
    vertical.grid(row=2, column=1, sticky="ns")
    e.canvas.configure(xscrollcommand=horizontal.set, yscrollcommand=vertical.set)
    e.canvas.bind("<Button-1>", e.click)
    e.canvas.bind("<B1-Motion>", e.drag)
    e.canvas.bind("<Button-3>", e.remove_vertex)
    e.canvas.bind("<MouseWheel>", e.wheel)
    e.canvas.bind("<Button-4>", lambda event: e.zoom(1.25, event))
    e.canvas.bind("<Button-5>", lambda event: e.zoom(0.8, event))
    e.canvas.bind("<ButtonPress-2>", lambda event: e.canvas.scan_mark(event.x, event.y))
    e.canvas.bind("<B2-Motion>", lambda event: e.canvas.scan_dragto(event.x, event.y, gain=1))
    legend = ttk.Frame(image_frame, padding=(12, 6))
    legend.grid(row=4, column=0, columnspan=2, sticky="ew")
    ttk.Label(legend, text="Blue: PNC+   Pink: PNC−   Gray: excluded", style="ReviewMuted.TLabel").pack(side="left")
    e.show_masks = tk.BooleanVar(value=True)
    e.show_ids = tk.BooleanVar(value=True)
    ttk.Checkbutton(legend, text="Outlines", variable=e.show_masks, command=e.render).pack(side="right")
    ttk.Checkbutton(legend, text="Numbers", variable=e.show_ids, command=e.render).pack(side="right", padx=10)

    sidebar = ttk.Frame(body, padding=(14, 10), style="ReviewPane.TFrame", width=285)
    sidebar.grid(row=0, column=1, sticky="nsew")
    sidebar.columnconfigure(0, weight=1)
    sidebar.rowconfigure(2, weight=1, minsize=35)
    e.sidebar = sidebar
    e.review_progress = tk.StringVar()
    ttk.Label(sidebar, text="Review nuclei", style="ReviewHeading.TLabel").grid(row=0, column=0, sticky="w")
    ttk.Label(sidebar, textvariable=e.review_progress, style="ReviewPane.TLabel").grid(row=1, column=0, sticky="w", pady=(2, 7))
    listing = ttk.Frame(sidebar, style="ReviewPane.TFrame")
    listing.grid(row=2, column=0, sticky="nsew")
    listing.columnconfigure(0, weight=1)
    listing.rowconfigure(1, weight=1)
    e.queue_filter = tk.StringVar(value="all")
    queue_filter = ttk.Combobox(listing, textvariable=e.queue_filter,
        values=("all", "unreviewed", "uncertain", "flagged", "rejected"), state="readonly", width=25)
    queue_filter.grid(row=0, column=0, columnspan=2, sticky="ew", pady=(0, 5))
    queue_filter.bind("<<ComboboxSelected>>", lambda _event: e.refresh())
    e.listbox = tk.Listbox(listing, width=27, height=5, selectmode="extended", exportselection=False,
        font=font, borderwidth=0, highlightthickness=1, highlightbackground="#dce1e7",
        selectbackground="#dceaff", selectforeground="#1c3e70", activestyle="none")
    e.listbox.grid(row=1, column=0, sticky="nsew")
    scroll = ttk.Scrollbar(listing, command=e.listbox.yview)
    scroll.grid(row=1, column=1, sticky="ns")
    e.listbox.configure(yscrollcommand=scroll.set)
    e.listbox.bind("<<ListboxSelect>>", e.select_list)
    e.list_ids = []
    e.selection_summary = tk.StringVar()
    ttk.Label(sidebar, textvariable=e.selection_summary, style="ReviewPane.TLabel", wraplength=255).grid(
        row=3, column=0, sticky="ew", pady=(12, 8))
    calls = ttk.Frame(sidebar, style="ReviewPane.TFrame")
    calls.grid(row=4, column=0, sticky="ew")
    e.manual_call = tk.StringVar(value="automatic")
    e.call_buttons = []
    for column, (label, value) in enumerate((("PNC+", "positive"), ("PNC−", "negative"), ("Auto", "automatic"))):
        widget = ttk.Radiobutton(calls, text=label, variable=e.manual_call, value=value,
            command=e.apply_manual_call, style="Review.TRadiobutton")
        widget.grid(row=0, column=column, sticky="ew")
        calls.columnconfigure(column, weight=1)
        e.buttons.append(widget)
        e.call_buttons.append(widget)
    e.exclude_label = tk.StringVar(value="Exclude nucleus")
    e.exclude_button = e.button(sidebar, "", e.toggle_exclusion, textvariable=e.exclude_label)
    e.exclude_button.grid(row=5, column=0, sticky="ew", pady=(10, 3))
    ttk.Label(sidebar, text="Bad or unwanted segmentation", style="ReviewPane.TLabel").grid(row=6, column=0, sticky="w")
    navigation = ttk.Frame(sidebar, style="ReviewPane.TFrame")
    navigation.grid(row=7, column=0, sticky="ew", pady=10)
    e.button(navigation, "←", lambda: e.next_in_queue(-1)).pack(side="left")
    e.button(navigation, "→", e.next_in_queue).pack(side="left", padx=4)
    e.check_button = e.button(navigation, "Checked & next", e.check_and_next)
    e.check_button.pack(side="right")
    e.more_button = e.button(sidebar, "More actions ▾", e.show_more_actions)
    e.more_button.grid(row=8, column=0, sticky="ew")
    e.more_menu = tk.Menu(e.window, tearoff=False)
    for label, command in (("Reviewer / note", e.edit_details), ("Flag for follow-up", lambda: e.mark(flagged=True)),
        ("Clear flag", lambda: e.mark(flagged=False)), ("Split nucleus", lambda: e.set_tool("Split")),
        ("Merge selected nuclei", e.merge), ("Delete selected nuclei", e.delete), ("Redo", e.redo),
        ("Reset to original", e.reset), ("Add verified reference", e.add_reference)):
        e.more_menu.add_command(label=label, command=command)
    e.more_menu.add_separator()
    e.more_menu.add_command(label="Advanced settings / details", command=e.show_advanced)

    footer = ttk.Frame(e.window, padding=(12, 6))
    footer.grid(row=3, column=0, sticky="ew")
    e.button(footer, "Fit image", e.fit).pack(side="left")
    e.button(footer, "+", lambda: e.zoom(1.25)).pack(side="left", padx=(6, 3))
    e.button(footer, "−", lambda: e.zoom(0.8)).pack(side="left")
    e.button(footer, "Display…", e.set_display_range).pack(side="left", padx=6)
    e.button(footer, "Advanced…", e.show_advanced).pack(side="right")
    e.status = tk.StringVar(value=e.session.warning or "Select a nucleus. Ctrl+click selects more than one.")
    ttk.Label(e.window, textvariable=e.status, style="ReviewMuted.TLabel", padding=(14, 4), wraplength=900).grid(
        row=4, column=0, sticky="ew")

    e.advanced_window = tk.Toplevel(e.window)
    e.advanced_window.withdraw()
    e.advanced_window.title("Review settings and details")
    e.advanced_window.transient(e.window)
    e.advanced_window.protocol("WM_DELETE_WINDOW", e.advanced_window.withdraw)
    advanced = ttk.Frame(e.advanced_window, padding=16)
    advanced.pack(fill="both", expand=True)
    ttk.Label(advanced, text="PNC method", style="ReviewTitle.TLabel").pack(anchor="w")
    e.pnc_method_box = ttk.Combobox(advanced, textvariable=e.pnc_method, values=tuple(methods), state="readonly", width=38)
    e.pnc_method_box.pack(fill="x", pady=8)
    e.pnc_method_box.bind("<<ComboboxSelected>>", e.schedule_pnc_preview)
    e.evidence_readout = tk.StringVar()
    ttk.Label(advanced, textvariable=e.evidence_readout, wraplength=420, style="Review.TLabel").pack(anchor="w", pady=8)
    e.z_controls = ttk.Frame(advanced)
    e.z_controls.pack(fill="x")
    e.button(e.z_controls, "Load Z evidence from source", e.load_z_evidence).pack(fill="x")
    e.button(e.z_controls, "Inspect candidate Z plane", e.inspect_z_plane).pack(fill="x", pady=4)
    e.button(e.z_controls, "Return to maximum projection", e.return_projection).pack(fill="x")
    if e.on_protocol:
        e.button(advanced, "Use for next analysis", e.use_pnc_protocol).pack(fill="x", pady=8)
    ttk.Separator(advanced).pack(fill="x", pady=8)
    e.detail = tk.StringVar()
    ttk.Label(advanced, textvariable=e.detail, wraplength=420, style="Review.TLabel").pack(anchor="w")
    ttk.Label(advanced, text="Numbers follow spatial order. Internal mask IDs stay unchanged.\nSave review creates a new revision; display contrast changes no measurements.",
        wraplength=420, style="ReviewMuted.TLabel").pack(anchor="w", pady=12)
    e.button(advanced, "Close", e.advanced_window.withdraw).pack(anchor="e")
    e.window.bind("<Return>", lambda _event: e.finish_outline())
    e.window.bind("<Escape>", lambda _event: e.cancel_outline())
    e.window.bind("<Control-z>", lambda _event: e.undo())
    e.window.bind("<Control-y>", lambda _event: e.redo())
    e.window.bind("<Control-s>", lambda _event: e.save())
